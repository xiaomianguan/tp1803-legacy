#!/usr/bin/env python3
"""Generate no-op stub libraries for vendor libraries a blob links against
but only uses on paths we never take (e.g. HIDL services that don't exist
on Android 6).

usage: gen-stubs.py <outdir> <client.so> <vendor libdir> <lib.so>... [-- extra=lib:symbol...]

For every symbol <client.so> imports from one of the given libs, emit:
  functions -> return 0 (and store a null sp<> through x8 for *getService)
  objects   -> zero-filled data of the original size
"""
import os, subprocess, sys
RE = os.path.expanduser("~/cm13-build/gpu/android-ndk-r27d/toolchains/llvm/prebuilt/linux-x86_64/bin/llvm-readelf")

def dynsyms(path):
    out = subprocess.run([RE, "--dyn-syms", "-W", path], capture_output=True, text=True).stdout
    res = []
    for l in out.splitlines():
        f = l.split()
        if len(f) < 8 or not f[0][:-1].isdigit(): continue
        res.append((f[7].split("@")[0], f[3], int(f[2], 0) if f[2].startswith("0x") else int(f[2]), f[6]))
    return res

args = sys.argv[1:]
extra = []
if "--" in args:
    i = args.index("--"); extra = args[i + 1:]; args = args[:i]
out, client, vdir, libs = args[0], args[1], args[2], args[3:]
need = {s for s, t, sz, ndx in dynsyms(client) if ndx == "UND"}
os.makedirs(out, exist_ok=True)
for lib in libs:
    defs = {s: (t, sz) for s, t, sz, ndx in dynsyms(os.path.join(vdir, lib)) if ndx != "UND"}
    syms = sorted(need & defs.keys())
    syms += [e.split(":", 1)[1] for e in extra if e.split(":", 1)[0] == lib]
    name = lib[:-3]
    with open(os.path.join(out, name + ".S"), "w") as f:
        f.write("/* Generated by tools/camera/gen-stubs.py: no-op stand-in for %s */\n" % lib)
        f.write(".text\n")
        for s in syms:
            t, sz = defs.get(s, ("FUNC", 0))
            if t == "OBJECT":
                f.write('.data\n.balign 16\n.globl %s\n.type %s,%%object\n.size %s,%d\n%s:\n.zero %d\n.text\n'
                        % (s, s, s, max(sz, 8), s, max(sz, 8)))
            else:
                body = "str xzr, [x8]\n" if s.endswith("GetServiceERKNSt3__112basic_stringIcNS2_11char_traitsIcEENS2_9allocatorIcEEEEb") or "getService" in s or "tryGetService" in s else ""
                f.write('.globl %s\n.type %s,%%function\n.balign 4\n%s:\n%smov x0, #0\nret\n' % (s, s, s, body))
    print("%s: %d symbols" % (lib, len(syms)))
